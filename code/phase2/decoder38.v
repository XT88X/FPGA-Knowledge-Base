//==============================================================================
// decoder38.v  —  可综合：3-8 译码器（使能 + 独热输出）
// 目标器件：通用 Xilinx Artix-7 / Zynq（7 系列）
//
// 原理：3 位地址 a[2:0] 译出 8 路独热输出 y[7:0]，同一时刻只有一路为 1。
//   en=1 时按 a 选通对应输出；en=0 时全部输出 0（关闭）。
//   例如 a=3'd0 -> y=8'b0000_0001；a=3'd5 -> y=8'b0010_0000。
// 这是纯组合逻辑：always @(*) + case，无时钟、无记忆。
//==============================================================================
`default_nettype none

module decoder38 (
    input  wire [2:0] a,    // 3 位地址输入
    input  wire       en,   // 高电平使能
    output reg  [7:0] y     // 8 路独热输出
);

    always @(*) begin
        if (!en) begin
            y = 8'b0000_0000;
        end else begin
            case (a)
                3'd0: y = 8'b0000_0001;
                3'd1: y = 8'b0000_0010;
                3'd2: y = 8'b0000_0100;
                3'd3: y = 8'b0000_1000;
                3'd4: y = 8'b0001_0000;
                3'd5: y = 8'b0010_0000;
                3'd6: y = 8'b0100_0000;
                3'd7: y = 8'b1000_0000;
                default: y = 8'b0000_0000;
            endcase
        end
    end

endmodule

`default_nettype wire
